#!/usr/bin/env bash
# Writes the ApplicationSets and the teams AppProject from platform/registry.yaml,
# platform/profiles/ and platform/subscriptions/.
#
# Usage: scripts/gen-appsets.sh [output dir]
#   With no argument it writes into the repo, where the root Application picks
#   the files up. One ApplicationSet per subscription, and one project:
#     argocd/apps-<cluster>/appsets/subscriptions/<team>-<name>.yaml
#     argocd/apps-<cluster>/projects/teams.yaml
#   With a directory it writes <cluster>-<team>-<name>.yaml and
#   teams-<cluster>.yaml there instead, and touches nothing in the repo. The
#   cutover uses that to stage the files before they go live.
#
# Each set reads one place: the subscription's config repository, at its
# repoPath, for <cluster>/*/env.yaml. Everything else it needs (the repository,
# the path, the service's identity, its profile) is written into the set here,
# from the subscription. ArgoCD never reads the subscription itself. That keeps
# each set to a single generator and means one set can only ever fail because of
# its own repository: an unreadable repository freezes its own set and no other.
#
# Each run first removes the sets it wrote last time, so a service whose
# subscription was deleted loses its generated file too.
#
# scripts/check-contract.sh regenerates into a temporary directory and fails if
# a committed file differs, so a hand edit or a stale copy cannot go unnoticed.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR/.."
source "$SCRIPT_DIR/reg.sh"

STAGE="${1:-}"

# out <cluster> <identity>, or out <cluster> teams: where a generated file goes.
out() {
  if [[ -n "$STAGE" ]]; then
    if [[ "$2" == teams ]]; then echo "$STAGE/teams-$1.yaml"; else echo "$STAGE/$1-$2.yaml"; fi
  elif [[ "$2" == teams ]]; then
    mkdir -p "argocd/apps-$1/projects"; echo "argocd/apps-$1/projects/teams.yaml"
  else
    mkdir -p "argocd/apps-$1/appsets/subscriptions"; echo "argocd/apps-$1/appsets/subscriptions/$2.yaml"
  fi
}

# Remove what the last run wrote. Only this script's own files: the add-ons
# set and anything else under argocd/ are left alone.
if [[ -n "$STAGE" ]]; then
  mkdir -p "$STAGE"
  for c in "${LFI_CLUSTERS[@]}"; do rm -f "$STAGE/$c-"*.yaml "$STAGE/teams-$c.yaml"; done
else
  for c in "${LFI_CLUSTERS[@]}"; do rm -f "argocd/apps-$c/appsets/subscriptions/"*.yaml; done
fi

for c in "${LFI_CLUSTERS[@]}"; do
  for sub in "$SUBSCRIPTIONS/$c"/*.yaml; do
    [[ -f "$sub" ]] || continue
    id="$(basename "$sub" .yaml)"
    team="$(yq '.team' "$sub")"
    profile="$(yq '.profile' "$sub")"
    repo="$(yq '.configRepo' "$sub")"
    path="$(yq '.repoPath // ""' "$sub")"
    pfile="$(profile_file "$profile")"
    [[ -f "$pfile" ]] || { echo "ERROR: $sub names profile '$profile', which has no $pfile." >&2; exit 1; }
    f="$(out "$c" "$id")"

    # The parts every set shares. The profile's parts are merged in below.
    cat > "$f" <<EOF
# $id on the $c cluster: one Application per environment the team has.
#
# Generated by scripts/gen-appsets.sh from platform/subscriptions/$c/$id.yaml
# and platform/profiles/$profile.yaml. Do not edit by hand: change those and
# regenerate.
#
# Which environments: every <env>/env.yaml under ${path:+$path/}$c/ in the team's
# config repository. The team adds an environment by adding a directory; nothing
# here changes, though its namespace must exist (Terraform creates
# <prefix>-<env> for each name in its environments variable).
apiVersion: argoproj.io/v1alpha1
kind: ApplicationSet
metadata:
  name: $c-$id
  namespace: argocd
  labels:
    platform/service: $id
    platform/team: $team
    platform/profile: $profile
spec:
  # Go templates, with an error on any missing key instead of a silent blank.
  goTemplate: true
  goTemplateOptions: ["missingkey=error"]
  generators:
    - git:
        repoURL: $repo
        revision: HEAD
        files:
          - path: '${path:+$path/}$c/*/env.yaml'
  template:
    metadata:
      name: '{{ .env }}-$id'
      labels:
        platform/service: $id
        platform/env: '{{ .env }}'
    spec:
      # Not "default": the teams project limits which repositories may be read,
      # which namespaces may be written, and forbids cluster-scoped resources.
      project: teams
      source:
        repoURL: $repo
        targetRevision: HEAD
        # path.path is the directory env.yaml sits in, for example ${path:+$path/}$c/dev.
        path: '{{ .path.path }}'
      destination:
        server: https://kubernetes.default.svc
        # A team may name its own namespace in env.yaml. The project still
        # refuses any that does not start with the platform's prefix.
        namespace: '{{ get . "namespace" | default (printf "%s-%s" "$NAMESPACE_PREFIX" .env) }}'
EOF
    # The profile: its policy merged into the set and into the template, and
    # its templatePatch, which is where a team's allowed overrides take effect.
    # The last line keeps every mapping in block style: merging a flow-style
    # map such as the profile's `set: {}` would otherwise turn the whole file
    # into one-line {...} style.
    P="$pfile" yq -i '
      . *= (load(strenv(P)).set // {}) |
      .spec.template *= (load(strenv(P)).template // {}) |
      .spec.templatePatch = load(strenv(P)).templatePatch |
      (.. | select(tag == "!!map")) style=""
    ' "$f"
  done

  cat > "$(out "$c" teams)" <<EOF
# What team-owned repositories are allowed to do on the $c cluster. Every
# Application the ApplicationSets create belongs to this project, so this file
# is the boundary between "the platform trusts the team's repo to say what runs"
# and "the team's repo can run anything it likes".
apiVersion: argoproj.io/v1alpha1
kind: AppProject
metadata:
  name: teams
  namespace: argocd
spec:
  description: Services whose manifests live in team-owned config repositories.
  # Any repository of this owner whose name ends in -config. Teams name their
  # own; scripts/check-contract.sh checks subscriptions against this pattern.
  sourceRepos:
    - https://github.com/$OWNER/*-config.git
  # Only the platform's namespaces. A team that sets namespace: kube-system in
  # its env.yaml gets a sync error, not a deployment into kube-system.
  destinations:
    - server: https://kubernetes.default.svc
      namespace: '$NAMESPACE_PREFIX-*'
  # Nothing cluster-wide: no Namespaces, ClusterRoles, CRDs or webhooks.
  clusterResourceWhitelist: []
  # Inside its namespaces a team may not grant itself access or lift its limits.
  namespaceResourceBlacklist:
    - group: rbac.authorization.k8s.io
      kind: Role
    - group: rbac.authorization.k8s.io
      kind: RoleBinding
    - group: ""
      kind: ResourceQuota
    - group: ""
      kind: LimitRange
EOF
done
